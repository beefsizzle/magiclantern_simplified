#ifndef _cameraspecific_gui_h_
#define _cameraspecific_gui_h_

/* M200: codes logged on the camera. Each real press is preceded by event
 * 0xA5 (generic user activity). 0xA5 (arg 1) also resets the timeout of the
 * LV Q-dialog the ML menu sits on, which closes ~10 s after the last one
 * (CONFIG_MENU_TIMEOUT_FIX). */
#define BGMT_USER_ACTIVITY           0xA5
#define BGMT_PRESS_RIGHT             0x3C
#define BGMT_UNPRESS_RIGHT           0x3D
#define BGMT_PRESS_LEFT              0x3E  // repeats with arg 0 while held
#define BGMT_UNPRESS_LEFT            0x3F
#define BGMT_PRESS_UP                0x40
#define BGMT_UNPRESS_UP              0x41
#define BGMT_PRESS_DOWN              0x42  // also the INFO key on M200
#define BGMT_UNPRESS_DOWN            0x43

/* Q/SET is one button */
#define BGMT_PRESS_SET               0x0A
#define BGMT_UNPRESS_SET             0x0B

#define BGMT_MENU                    0x0C  // unpress 0x0D
#define BGMT_PLAY                    0x12  // unpress 0x13

/* Top dial: 0x09 = clockwise, 0x08 = counter-clockwise */
#define BGMT_WHEEL_LEFT              0x08
#define BGMT_WHEEL_RIGHT             0x09

#define BGMT_PRESS_HALFSHUTTER       0x9D  // unpress 0x9E (also 0xA1 / 0xA2 alongside)

/* M200 has no separate INFO, Trash or M.Fn button: INFO is DOWN (0x42).
 * These are placeholder codes the camera never sends (same convention as
 * the 0xE0-0xF9 block below). BGMT_TRASH is generated by the long-press
 * handler in menu.c: hold INFO/DOWN for ~0.5 s to open the ML menu. */
#define BGMT_INFO                    0xFB
#define BGMT_TRASH                   0xFA
/* No Q button either (Q/SET is one button): long press SET in the ML menu
 * sends this placeholder as Q, to open submenus (CONFIG_LONG_PRESS_SET_MENU) */
#define BGMT_Q                       0xFC

/* Seen but not mapped yet:
 * - mode dial turned to movie: 0xCC/0xCD with 0xBD/0xBE/0xC3 (arg 0xC), no 0xA5
 *   before it, followed by 0xB5 arg 0x23 / 0x13 (mode change notifications)
 * - screen tap: 0xBD/0xBE (arg 0xC)
 */

/* Red movie record button. Lets mlv_lite take over the record button
 * when RAW video is enabled in the ML menu. */
#define BGMT_REC                     0x2D
#define BGMT_UNPRESS_REC             0x2E

/* WRONG: DNE in M50 */
#define BGMT_PRESS_UP_RIGHT          0xF0
#define BGMT_PRESS_UP_LEFT           0xF1
#define BGMT_PRESS_DOWN_RIGHT        0xF2
#define BGMT_PRESS_DOWN_LEFT         0xF3

#define BGMT_JOY_CENTER              0xF4

#define BGMT_WHEEL_UP                0xF5
#define BGMT_WHEEL_DOWN              0xF6
#define BGMT_LV                      0xF7
/* what is that ?! */
#define BGMT_UNPRESS_UDLR            0xF8

#define BGMT_PRESS_ZOOM_IN           0xF9
#define BGMT_UNPRESS_ZOOM_IN         0xE0
#define BGMT_PRESS_ZOOM_OUT          0xE1
#define BGMT_UNPRESS_ZOOM_OUT        0xE2
#define BGMT_PICSTYLE                0xE3

#define BGMT_FLASH_MOVIE             0xE4
#define BGMT_PRESS_FLASH_MOVIE       0xE5
#define BGMT_UNPRESS_FLASH_MOVIE     0xE6

#define BGMT_ISO_MOVIE               0xE7
#define BGMT_PRESS_ISO_MOVIE         0xE8
#define BGMT_UNPRESS_ISO_MOVIE       0xE9

/* WRONG: to be checked */
// backtrace copyOlcDataToStorage call in gui_massive_event_loop
#define GMT_OLC_INFO_CHANGED         59

// needed for correct shutdown from powersave modes
#define GMT_GUICMD_START_AS_CHECK    43
#define GMT_GUICMD_OPEN_SLOT_COVER   40
#define GMT_GUICMD_LOCK_OFF          38

#define BTN_ZEBRAS_FOR_PLAYBACK      BGMT_FUNC // what button to use for zebras in Play mode
#define BTN_ZEBRAS_FOR_PLAYBACK_NAME "FUNC"

#endif
